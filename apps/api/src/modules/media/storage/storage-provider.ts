/**
 * Object storage used by the media pipeline. Two buckets: `public` (catalogue media, served via
 * CDN) and `private` (e.g. return evidence, only reachable through short-lived signed URLs).
 * Implementations: R2 (S3 API) and LocalMock (files on disk; dev/test without keys).
 */
export type Bucket = 'public' | 'private';

export interface PresignedUpload {
  url: string;
  method: 'PUT';
  /** Headers the client must send unchanged (the signature covers them). */
  headers: Record<string, string>;
  expiresAt: Date;
}

export interface ObjectHead {
  contentLength: number;
  contentType: string | undefined;
}

export interface PresignedUploadInput {
  bucket: Bucket;
  key: string;
  contentType: string;
  /** Exact byte size; the signature (R2) or token (local) only accepts this length. */
  contentLength: number;
  expiresInSeconds: number;
}

export interface StorageProvider {
  readonly driver: 'local' | 'r2';
  createPresignedUpload(input: PresignedUploadInput): Promise<PresignedUpload>;
  /** undefined when the object does not exist. */
  headObject(bucket: Bucket, key: string): Promise<ObjectHead | undefined>;
  /** First `length` bytes (ranged read), for magic-byte checks. */
  readRange(bucket: Bucket, key: string, length: number): Promise<Buffer>;
  downloadToFile(bucket: Bucket, key: string, filePath: string): Promise<void>;
  uploadFile(bucket: Bucket, key: string, filePath: string, contentType: string): Promise<void>;
  /** Stable URL of an object in the PUBLIC bucket. */
  getPublicUrl(key: string): string;
  /** Short-lived URL for an object in the PRIVATE bucket. */
  createPrivateSignedUrl(key: string, expiresInSeconds: number): Promise<string>;
  /** Deleting a missing object is not an error. */
  delete(bucket: Bucket, key: string): Promise<void>;
}

/** Object keys are generated by the API (never from user input); anything else is refused. */
export const OBJECT_KEY_PATTERN = /^[a-z0-9][a-z0-9/_.-]{0,500}$/;

export function assertSafeKey(key: string): void {
  if (!OBJECT_KEY_PATTERN.test(key) || key.includes('..') || key.includes('//')) {
    throw new Error(`Refusing unsafe object key: ${key}`);
  }
}
